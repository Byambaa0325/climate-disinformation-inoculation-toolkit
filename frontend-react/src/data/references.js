/** Get reference by id (e.g. 'cook2017'). */
export function getRef(id) {
  return REFERENCES.find((r) => r.id === id) || null;
}

/** Get URL for a reference id; returns '#' if not found (anchor to References section). */
export function getRefUrl(id) {
  const ref = getRef(id);
  return ref?.url || '#references';
}
